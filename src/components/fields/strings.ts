/** A stored label as the reader sees it: the translated word if it is one of the offered words, else as written. */
export function presetLabel(stored: string, locale: Locale): string {
  const w = PRESET[stored];
  return w ? w[locale === 'de' ? 1 : 0] : stored;
}

export type Vars = Record<string, string | number>;
export type Copy = ((key: CopyKey, vars?: Vars) => string) & { locale: Locale };

const fill = (text: string, vars?: Vars) => (vars ? text.replace(/\{(\w+)\}/g, (all, k) => (vars[k] !== undefined ? String(vars[k]) : all)) : text);

/** The copy for the reader's language. Takes the locale from `useT()`, so it follows the language switch. */
export function useCopy(): Copy {
  const t = useT();
  const dict: Record<CopyKey, string> = t.locale === 'de' ? DE : (EN as Record<CopyKey, string>);
  return Object.assign((key: CopyKey, vars?: Vars) => fill(dict[key] ?? EN[key], vars), { locale: t.locale });
}
