export type G = (key: GKey, vars?: Record<string, string | number>) => string;

/** The gallery's words in the reader's language: `const g = useG(); g('gallery.add')`. */
export function useG(): G {
  const { locale } = useT();
  return (key, vars) => format(locale, key, vars);
}

/** Plain formatting without a hook, for code outside React. */
export function format(locale: string, key: GKey, vars: Record<string, string | number> = {}): string {
  const dict = locale === 'de' ? DE : EN;
  const entry = dict[key] ?? EN[key];
  const text = typeof entry === 'string' ? entry : entry[new Intl.PluralRules(locale === 'de' ? 'de-DE' : 'en-GB').select(Number(vars.count ?? 0)) === 'one' ? 'one' : 'other'];
  return text.replace(/\{(\w+)\}/g, (all, k) => {
    const v = vars[k];
    if (v === undefined) return all;
    return typeof v === 'number' ? new Intl.NumberFormat(locale === 'de' ? 'de-DE' : 'en-GB').format(v) : v;
  });
}
