export type ExKey = keyof typeof en;

/** The text for `key` in `locale`, with {name} placeholders filled in. English is used where German is missing. */
export function ex(locale: Locale, key: ExKey, vars: Record<string, string | number> = {}): string {
  const text = (locale === 'de' ? de[key] : undefined) ?? en[key];
  return text.replace(/\{(\w+)\}/g, (all, k) => (vars[k] === undefined ? all : typeof vars[k] === 'number' ? new Intl.NumberFormat(locale === 'de' ? 'de-DE' : 'en-GB').format(vars[k] as number) : String(vars[k])));
}
