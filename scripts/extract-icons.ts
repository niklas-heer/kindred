// Writes src/components/charges.gen.ts with only the game-icons bodies the app draws (heraldic
// charges, headwear badges, occasions and traits), so the client bundle does not carry the whole icon set.
// Run with: node scripts/extract-icons.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { iconToSVG } from '@iconify/utils';

const NAMES = [
  'boar',
  'broadsword',
  'crown',
  'eagle-emblem',
  'fleur-de-lys',
  'key',
  'laurel-crown',
  'lion',
  'moon',
  'pope-crown',
  'rose',
  'stag-head',
  'star-formation',
  'tower-flag',
  // Facts about people: occasions, stories, uncertainty.
  'cake-slice',
  'linked-rings',
  'candle-light',
  'quill-ink',
  'uncertainty',
  'wax-seal',
  // Traits.
  'sword-brandish', 'run', 'prayer', 'shrug', 'open-book', 'sprout', 'bow-arrow', 'lyre', 'enrage', 'hourglass',
  'open-treasure-chest', 'coins', 'scales', 'mountain-climbing', 'meditation', 'beer-stein', 'hood', 'lily-pads',
  'lips', 'chess-knight',
];

interface IconSet {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
}

const set = JSON.parse(
  readFileSync(new URL('../node_modules/@iconify-json/game-icons/icons.json', import.meta.url), 'utf8'),
) as IconSet;

const entries = NAMES.map((name) => {
  const icon = set.icons[name];
  if (!icon) throw new Error(`game-icons has no icon "${name}"`);
  const { attributes, body } = iconToSVG({ left: 0, top: 0, width: set.width ?? 512, height: set.height ?? 512, ...icon });
  return { name, viewBox: attributes.viewBox, body };
});

const out = `// Generated by scripts/extract-icons.ts from @iconify-json/game-icons (Lorc and Delapouite, CC BY 3.0).
// Do not edit by hand; run \`node scripts/extract-icons.ts\` to regenerate.

export type ChargeIconName = ${NAMES.map((n) => `'${n}'`).join(' | ')};

export const CHARGE_ICONS: Record<ChargeIconName, { viewBox: string; body: string }> = {
${entries.map((e) => `  '${e.name}': { viewBox: '${e.viewBox}', body: ${JSON.stringify(e.body)} },`).join('\n')}
};
`;

writeFileSync(new URL('../src/components/charges.gen.ts', import.meta.url), out);
console.log(`wrote ${entries.length} icons, ${out.length} bytes`);
