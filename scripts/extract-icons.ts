// Extracts the game-icons.net glyphs the app draws, so no bundle carries the whole icon set.
//
// - src/components/charges.gen.ts: the main bundle. The v1 heraldic charges every old shield uses, the
//   headwear badges, and the glyphs for occasions and traits.
// - src/components/heraldry/library/charges.gen.ts: the charges added with the library, read from
//   scripts/charge-library.tsv (id, glyph, category, the three names, search words, flags). Loaded on demand.
// - src/components/heraldry/library/glyphs/<category>.gen.ts: the glyphs of the other heraldry charges, one
//   module per category, so a shield loads only the categories it draws. Loaded on demand (see heraldry/art.ts).
//
// Run with: node scripts/extract-icons.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { iconToSVG } from '@iconify/utils';
import { CHARGES_V2, HELM_GLYPH, type ChargeCategory } from '../src/lib/heraldry/catalogue.ts';

const CORE = [
  'boar',
  'broadsword',
  'crown',
  'eagle-emblem',
  'fleur-de-lys',
  'key',
  'laurel-crown',
  'lion',
  'moon',
  'pope-crown',
  'rose',
  'stag-head',
  'star-formation',
  'tower-flag',
  // Facts about people: occasions, stories, uncertainty.
  'cake-slice',
  'linked-rings',
  'candle-light',
  'quill-ink',
  'uncertainty',
  'wax-seal',
  // Traits.
  'sword-brandish', 'run', 'prayer', 'shrug', 'open-book', 'sprout', 'bow-arrow', 'lyre', 'enrage', 'hourglass',
  'open-treasure-chest', 'coins', 'scales', 'mountain-climbing', 'meditation', 'beer-stein', 'hood', 'lily-pads',
  'lips', 'chess-knight',
];

interface IconSet {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
}

const set = JSON.parse(
  readFileSync(new URL('../node_modules/@iconify-json/game-icons/icons.json', import.meta.url), 'utf8'),
) as IconSet;

function extract(name: string, keepFill = false) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`game-icons has no icon "${name}"`);
  const { attributes, body } = iconToSVG({ left: 0, top: 0, width: set.width ?? 512, height: set.height ?? 512, ...icon });
  // Every glyph is one or more filled paths in currentColor. Library glyphs drop the attribute, since the heraldry
  // renderer sets the fill on a wrapping group (so a mask can paint the same glyph white).
  return { name, viewBox: attributes.viewBox, body: keepFill ? body : body.replace(/ fill="currentColor"/g, '') };
}

/**
 * One decimal place is finer than any shield's pixels, and it cuts the library's glyph modules by about a quarter.
 * Every number keeps its decimal point: "2.0" and "0.3" stay apart, where "2" and "0.3" would run together as "20.3".
 */
function oneDecimal(body: string): string {
  return body.replace(/-?\d*\.\d+/g, (m) => {
    const v = Math.round(Number(m) * 10) / 10;
    return (Math.abs(v) < 0.05 ? 0 : v).toFixed(1);
  });
}

const HEADER = `// Generated by scripts/extract-icons.ts from @iconify-json/game-icons (Lorc, Delapouite and contributors, CC BY 3.0).
// Do not edit by hand; run \`node scripts/extract-icons.ts\` to regenerate.
`;

// ---- the curated library rows ----

interface LibraryRow {
  id: string;
  gi: string;
  cat: ChargeCategory;
  keys: string;
  facing: boolean;
}

const LIBRARY_CATEGORIES: ChargeCategory[] = [
  'crosses', 'beasts', 'birds', 'sea', 'monsters', 'plants', 'celestial', 'weapons', 'tools', 'buildings', 'crowns', 'objects', 'faith', 'body', 'music',
];

const rows: LibraryRow[] = readFileSync(new URL('./charge-library.tsv', import.meta.url), 'utf8')
  .split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((line) => {
    const [id, gi, cat, keys, flags = ''] = line.split('|');
    if (!id || !gi || !cat || !keys) throw new Error(`charge-library.tsv: a row is incomplete: ${line}`);
    if (!LIBRARY_CATEGORIES.includes(cat as ChargeCategory)) throw new Error(`charge-library.tsv: ${id} has no category "${cat}"`);
    return { id, gi, cat: cat as ChargeCategory, keys, facing: flags.split(' ').includes('f') };
  });

const seen = new Set<string>();
for (const r of rows) {
  if (seen.has(r.id)) throw new Error(`charge-library.tsv: id "${r.id}" is listed twice`);
  seen.add(r.id);
  if (CHARGES_V2.some((c) => c.id === r.id)) throw new Error(`charge-library.tsv: id "${r.id}" is already a catalogue charge`);
}

for (const c of CHARGES_V2) if (c.core && c.gi && !CORE.includes(c.gi)) throw new Error(`core charge ${c.id} uses ${c.gi}, which is not in CORE`);

// The core file keeps fill="currentColor" on each path: GameIcon and the portraits draw its bodies directly.
const core = CORE.map((name) => extract(name, true));
const coreOut = `${HEADER}
export type ChargeIconName = ${CORE.map((n) => `'${n}'`).join(' | ')};

export const CHARGE_ICONS: Record<ChargeIconName, { viewBox: string; body: string }> = {
${core.map((e) => `  '${e.name}': { viewBox: '${e.viewBox}', body: ${JSON.stringify(e.body)} },`).join('\n')}
};
`;
writeFileSync(new URL('../src/components/charges.gen.ts', import.meta.url), coreOut);
console.log(`core: ${core.length} icons, ${coreOut.length} bytes`);

// ---- the library: metadata for the new charges, and glyphs by category ----

const libraryDir = new URL('../src/components/heraldry/library/', import.meta.url);
mkdirSync(new URL('glyphs/', libraryDir), { recursive: true });

const metaOut = `${HEADER}// The charges added to the heraldry library, from scripts/charge-library.tsv. Loaded on demand (heraldry/art.ts).
import type { ChargeDef } from '../../../lib/heraldry/catalogue.ts';

export const LIBRARY_CHARGES: ChargeDef[] = [
${rows.map((r) => `  { id: ${JSON.stringify(r.id)}, gi: ${JSON.stringify(r.gi)}, cat: '${r.cat}', label: ${JSON.stringify(`heraldry.library.${r.id}`)}, keys: ${JSON.stringify(r.keys)}${r.facing ? ', facing: true' : ''} },`).join('\n')}
];
`;
writeFileSync(new URL('charges.gen.ts', libraryDir), metaOut);
console.log(`library metadata: ${rows.length} charges, ${metaOut.length} bytes`);

// Every non-core glyph a heraldry charge draws, grouped by its charge's category. The helms of the achievement are
// drawn from the weapons module.
const byCategory = new Map<ChargeCategory, Set<string>>();
const add = (cat: ChargeCategory, gi: string) => {
  if (CORE.includes(gi)) return;
  if (!byCategory.has(cat)) byCategory.set(cat, new Set());
  byCategory.get(cat)!.add(gi);
};
for (const c of CHARGES_V2) if (c.gi && c.cat !== 'classic') add(c.cat, c.gi);
for (const r of rows) add(r.cat, r.gi);
for (const h of Object.values(HELM_GLYPH)) add('weapons', h.gi);

let glyphBytes = 0;
let glyphCount = 0;
for (const cat of [...byCategory.keys()].sort()) {
  const names = [...byCategory.get(cat)!].sort();
  const glyphs = names.map((n) => {
    const e = extract(n);
    return { ...e, body: oneDecimal(e.body) };
  });
  const out = `${HEADER}// The ${cat} glyphs of the heraldry library. Bodies are paths without a fill: the renderer sets it.

export const GLYPHS: Record<string, { viewBox: string; body: string }> = {
${glyphs.map((e) => `  '${e.name}': { viewBox: '${e.viewBox}', body: ${JSON.stringify(e.body)} },`).join('\n')}
};
`;
  writeFileSync(new URL(`glyphs/${cat}.gen.ts`, libraryDir), out);
  glyphBytes += out.length;
  glyphCount += glyphs.length;
  console.log(`glyphs/${cat}: ${glyphs.length} icons, ${out.length} bytes`);
}
console.log(`library glyphs: ${glyphCount} icons in ${byCategory.size} modules, ${glyphBytes} bytes`);
